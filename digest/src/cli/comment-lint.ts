import { readdirSync, readFileSync } from "node:fs";
import { extname, join } from "node:path";
import { parseSync } from "oxc-parser";

export const MESSAGE = [
  "No comments in digest/src, digest/templates or design/ (CLAUDE.md, Don't): delete each one listed above.",
  "Put a rule in a test, type or schema, and a test's reason in its name; git holds the history.",
  "Only directives (oxlint-disable with a reason, @ts-expect-error, @vitest-environment) and generated banners stay.",
].join("\n");

export interface Comment {
  type: string;
  start: number;
  end: number;
  value: string;
}

export const ALLOWED: Record<string, RegExp> = {
  lint: /^(?:oxlint|eslint)-disable(?:-next-line|-line)?\s+[\w/@-]+(?:\s*,\s*[\w/@-]+)*\s+--\s+\S[^\r\n]*$/,
  "lint-enable": /^(?:oxlint|eslint)-enable\s+[\w/@-]+(?:\s*,\s*[\w/@-]+)*$/,
  "ts-error": /^@ts-(?:expect-error|ignore)(?:\s+[^\r\n]+)?$/,
  "ts-check": /^@ts-(?:check|nocheck)$/,
  reference: /^\/\s*<reference\s+(?:types|path|lib|no-default-lib)\s*=\s*["'][^"'\r\n]+["']\s*\/>$/,
  annotation: /^(?:#|@)__(?:PURE|NO_SIDE_EFFECTS)__$/,
  vitest: /^@vitest-environment\s+[\w-]+$/,
  generated: /^Generated by\s+\S[^\r\n]*$/i,
  licence:
    /^(?:!\s*)?(?:@license\b|@licence\b|@preserve\b|SPDX-License-Identifier:|Copyright\s+(?:\(c\)\s*)?\d{4})[\s\S]*$/i,
};

export function allowedKind(comment: Comment, source: string): string | null {
  const body = comment.value
    .trim()
    .replace(/^\*\s?/, "")
    .trim();
  for (const [kind, regex] of Object.entries(ALLOWED)) {
    if (!regex.test(body)) continue;
    if ((kind === "generated" || kind === "licence") && source.slice(0, comment.start).trim()) continue;
    return kind;
  }
  return null;
}

export function cssComments(source: string): Comment[] {
  const comments: Comment[] = [];
  const stringEnd = (start: number): number => {
    const quote = source[start];
    let i = start + 1;
    while (i < source.length) {
      if (source[i] === "\\") i += 2;
      else if (source[i++] === quote) return i;
    }
    throw new Error("Unterminated CSS string");
  };
  for (let i = 0; i < source.length;) {
    if (source[i] === "\\") {
      i += 2;
      continue;
    }
    if (source[i] === '"' || source[i] === "'") {
      i = stringEnd(i);
      continue;
    }
    const url = /^url\s*\(/i.exec(source.slice(i));
    if (url && (i === 0 || !/[\w-]/.test(source[i - 1]!))) {
      i += url[0].length;
      while (i < source.length && source[i] !== ")") {
        if (source[i] === "\\") i += 2;
        else if (source[i] === '"' || source[i] === "'") i = stringEnd(i);
        else i++;
      }
      i++;
      continue;
    }
    if (source.startsWith("/*", i)) {
      const end = source.indexOf("*/", i + 2);
      if (end < 0) throw new Error("Unterminated CSS comment");
      comments.push({ type: "Block", start: i, end: end + 2, value: source.slice(i + 2, end) });
      i = end + 2;
    } else i++;
  }
  return comments;
}

export function commentsOf(file: string, source: string): Comment[] {
  if (extname(file) === ".css") return cssComments(source);
  const parsed = parseSync(file, source);
  if (parsed.errors.length) throw new Error(`${file}: ${parsed.errors.map((e) => e.message).join("; ")}`);
  return parsed.comments;
}

const SKIPPED = /(?:^|\/)(?:fixtures|node_modules|dist)(?:\/|$)|schema\.gen\.ts$/;

export function sourceFiles(root: string): string[] {
  return readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && /\.(?:js|ts|mjs|css)$/.test(entry.name))
    .map((entry) => join(entry.parentPath, entry.name))
    .filter((file) => !SKIPPED.test(file))
    .toSorted();
}

export const lineOf = (source: string, offset: number): number => source.slice(0, offset).split("\n").length;

export function lint(...roots: string[]): string[] {
  if (!roots.length) roots = ["src", "templates", "../design"];
  const failures: string[] = [];
  for (const file of roots.flatMap(sourceFiles)) {
    const source = readFileSync(file, "utf8");
    for (const comment of commentsOf(file, source)) {
      if (!allowedKind(comment, source)) failures.push(`${file}:${lineOf(source, comment.start)}`);
    }
  }
  return failures;
}

if (import.meta.main) {
  try {
    const failures = lint(...process.argv.slice(2));
    if (failures.length) {
      console.error(`${failures.join("\n")}\n${MESSAGE}`);
      process.exitCode = 1;
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
