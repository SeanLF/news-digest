import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseSync } from "oxc-parser";
import { expect, onTestFinished, test } from "vitest";
import { MESSAGE } from "./comment-lint.js";

const script = new URL("./comment-lint.ts", import.meta.url).pathname;
const ROOTS = ["src", "templates", "design"];

function run(files: Record<string, string>, roots?: string[]) {
  const root = mkdtempSync(join(tmpdir(), "comment-lint-"));
  onTestFinished(() => rmSync(root, { recursive: true, force: true }));
  for (const [file, source] of Object.entries(files)) {
    const path = join(root, file);
    mkdirSync(join(path, ".."), { recursive: true });
    writeFileSync(path, source);
  }
  for (const folder of ROOTS) mkdirSync(join(root, folder), { recursive: true });
  const args = roots === undefined ? [root] : roots.map((folder) => join(root, folder));
  const result = spawnSync(process.execPath, [script, ...args], { cwd: root, encoding: "utf8" });
  expect(result.error).toBeUndefined();
  expect(result.signal).toBeNull();
  return { ...result, root };
}

const allowed = [
  "// oxlint-disable-next-line no-console -- the CLI's output",
  "/* oxlint-disable typescript/no-unsafe-type-assertion -- a generated fixture */",
  "/* oxlint-enable typescript/no-unsafe-type-assertion */",
  "// eslint-disable-line no-await-in-loop -- one request at a time",
  "// @ts-expect-error intentional type failure",
  "// @ts-ignore legacy caller",
  "// @ts-check",
  "// @ts-nocheck",
  '/// <reference types="node" />',
  "/*#__PURE__*/",
  "/*@__NO_SIDE_EFFECTS__*/",
  ["// @vitest", "environment node"].join("-"),
  "// Generated by kysely-codegen from the schema",
  "/* @license MIT */",
  "/* SPDX-License-Identifier: MIT */",
];
test("one file per allowed directive or banner passes", () => {
  const files = Object.fromEntries(allowed.map((c, i) => [`allowed-${i}.ts`, c + "\nexport const value = 1;\n"]));
  files["generated.css"] = "/* Generated by a build step */\na {color:red}";
  const result = run(files);
  expect(result.stderr).toBe("");
  expect(result.status).toBe(0);
});

const forbidden: Record<string, string> = {
  "line.ts": "\n// a rule\nconst value = 1;",
  "block.ts": "\n/* a rule */\nconst value = 1;",
  "doc.mjs": "\n/** @param {string} value */\nconst value = 1;",
  "nested/trailing.ts": "\nconst value = 1; // a rule",
  "style.css": "\na {color:red; /* a rule */}",
  "unreasoned.ts": "\n// oxlint-disable-next-line no-console\nconsole.log(1);",
  "enable-reason.ts": "\n// oxlint-enable no-console -- a reason belongs on the disable\nconst value = 1;",
  "pretend.ts": "\n// oxlint-disableish no-console -- not a directive",
  "mentions.ts": "\n// Discuss @ts-check here",
  "banner.ts": "const value = 1;\n// Generated by a person",
  "licence.ts": "const value = 1;\n/* @license MIT */",
  "annotation.ts": "\n/* @__PURE__ explanation */",
  "empty.ts": "\n//",
};
for (const [file, source] of Object.entries(forbidden)) {
  test(`${file} fails with its exact file and line`, () => {
    const result = run({ [file]: source });
    expect(result.status).toBe(1);
    expect(result.stderr.trim()).toBe(`${join(result.root, file)}:2\n${MESSAGE}`);
  });
}

test("comment-looking strings, templates, regexes and CSS urls pass", () => {
  const result = run({
    "text.ts": 'const text = "é😀 // not a comment"; const template = `/* text */`; const pattern = /\\/\\*text/;',
    "text.css":
      'a {content:"escaped \\" /* text */"; background:URL(data:image/svg+xml;/*text*/); mask:url("/*text*/"); other:url(data:text/plain,escaped\\)/*text*/);}',
  });
  expect(result.stderr).toBe("");
  expect(result.status).toBe(0);
});

test("CSS scanning resumes after strings and urls", () => {
  const result = run({ "text.css": 'a{content:"/* text */";background:url(data:/*text*/);}\n/* forbidden */' });
  expect(result.status).toBe(1);
  expect(result.stderr).toContain(`${join(result.root, "text.css")}:2\n`);
});

test("oxc comment offsets index UTF-16 after non-ASCII text", () => {
  const source = 'const text = "é😀漢"; // forbidden\n';
  const [comment] = parseSync("unicode.ts", source).comments;
  expect(comment!.start).toBe(source.indexOf("//"));
  expect(source.slice(comment!.start, comment!.end)).toBe("// forbidden");
});

test("every violation is reported, in every root; fixtures, dist and the generated schema are skipped", () => {
  const result = run({ "nested/code.test.ts": "// first\nconst x = 1; // second\n", "style.css": "/* third */" });
  expect(result.status).toBe(1);
  for (const location of ["nested/code.test.ts:1", "nested/code.test.ts:2", "style.css:1"])
    expect(result.stderr).toContain(join(result.root, location));
  for (const folder of ROOTS) {
    const planted = run({ [`${folder}/planted.ts`]: "// forbidden\n" }, [folder]);
    expect(planted.status).toBe(1);
    expect(planted.stderr.trim()).toBe(`${join(planted.root, folder, "planted.ts")}:1\n${MESSAGE}`);
  }
  const skipped = run(
    {
      "src/fixtures/data.ts": "// fixture\n",
      "src/dist/out.js": "// built\n",
      "src/store/schema.gen.ts": "/** This file was generated by kysely-codegen. */\n",
    },
    ["src"],
  );
  expect(skipped.stderr).toBe("");
  expect(skipped.status).toBe(0);
});

test("parse errors and broken CSS fail closed", () => {
  for (const [file, source] of [
    ["broken.ts", "const = ;"],
    ["broken.css", "/* unfinished"],
  ] as const) {
    const result = run({ [file]: source });
    expect(result.status).toBe(1);
    expect(result.stderr.length).toBeGreaterThan(0);
  }
});

test("the message names the fix and where the rule is written", () => {
  expect(MESSAGE).toMatch(/delete each one/);
  expect(MESSAGE).toMatch(/CLAUDE\.md/);
  expect(MESSAGE.split("\n").length).toBeLessThanOrEqual(3);
});
